// Pull each HostAway listing's photo gallery and write data/listingPhotos.ts.
// One-off / occasional: re-run when the photos change in HostAway.
//   node scripts/fetch-listing-photos.mjs
// Credentials come from the same Firebase secrets the functions use:
//   firebase functions:secrets:access HOSTAWAY_ACCOUNT_ID / HOSTAWAY_API_KEY
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const LISTING_IDS = [345789, 345790, 345792, 345787, 345791, 345786, 563826, 559483, 345788];
const MAX_PER_LISTING = 12;

const secret = (name) =>
  execSync(`firebase functions:secrets:access ${name}`, { encoding: 'utf8' }).trim();

const clientId = secret('HOSTAWAY_ACCOUNT_ID');
const clientSecret = secret('HOSTAWAY_API_KEY');

const tokenRes = await fetch('https://api.hostaway.com/v1/accessTokens', {
  method: 'POST',
  headers: { 'Content-Type': 'application/x-www-form-urlencoded', 'Cache-control': 'no-cache' },
  body: new URLSearchParams({
    grant_type: 'client_credentials',
    client_id: clientId,
    client_secret: clientSecret,
    scope: 'general',
  }),
});
const token = (await tokenRes.json()).access_token;
if (!token) throw new Error('Could not authenticate with HostAway.');

const map = {};
for (const id of LISTING_IDS) {
  const res = await fetch(`https://api.hostaway.com/v1/listings/${id}`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  const json = await res.json();
  const imgs = (json.result?.listingImages ?? [])
    .slice()
    .sort((a, b) => (a.sortOrder ?? 0) - (b.sortOrder ?? 0))
    .map((i) => i.url)
    .filter(Boolean)
    .slice(0, MAX_PER_LISTING);
  map[id] = imgs;
  console.log(`listing ${id}: ${imgs.length} photos`);
}

const body = `// AUTO-GENERATED by scripts/fetch-listing-photos.mjs — do not edit by hand.
// HostAway listing galleries, keyed by listing id. Re-run the script to refresh.
export const LISTING_PHOTOS: Record<number, string[]> = ${JSON.stringify(map, null, 2)};
`;
writeFileSync(new URL('../data/listingPhotos.ts', import.meta.url), body);
console.log('Wrote data/listingPhotos.ts');
